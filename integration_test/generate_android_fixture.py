"""Generate synthetic SM4 library/ticket fixtures; no campus data or credentials."""
import base64
import lzma
from pathlib import Path
import random
import struct
import subprocess

module = bytearray(random.Random(17369).randbytes(4096))
module[:4] = b"\x7fELF"
struct.pack_into("<Q", module, 0x20, 0x40)
struct.pack_into("<HH", module, 0x36, 56, 1)
struct.pack_into("<IIQQ", module, 0x40, 1, 6, 0x100, 0xB000)
struct.pack_into("<Q", module, 0x40 + 32, 0x800)
module[0x100 + 0x43:0x100 + 0x53] = bytes(range(16))
module[0x100 + 0xF9 + 2] = 16
module[0x100 + 0xF9 + 5] = 0x43
module[0x500:0x50A] = b"tpl_sm4.so"
compressed = lzma.compress(bytes(module), format=lzma.FORMAT_RAW, filters=[
    {"id": lzma.FILTER_LZMA1, "dict_size": 1 << 24, "lc": 3, "lp": 0, "pb": 2}
])
payload = bytes(a ^ b for a, b in zip(compressed[:-1], compressed[1:])) + compressed[-1:]
library = (b"001\x40" + b"0" * 64 + b"$" + b"00000000-0000-0000-0000-000000000001]"
           + b"\0" * 4 + struct.pack("<I", len(module)) + payload)
ticket = b"<ticket>1234567890abcdef1234567890abcdef</ticket>"
ticket += b"\0" * (-len(ticket) % 16)
encrypted = subprocess.run(
    ["openssl", "enc", "-sm4-ecb", "-K", bytes(range(16)).hex(), "-nopad"],
    input=ticket, capture_output=True, check=True).stdout.hex()
Path(__file__).with_name("android_loopback_fixture.dart").write_text(
    "// Generated by generate_android_fixture.py; synthetic data only.\n"
    f"const loopbackLibrary = '{base64.b64encode(library).decode()}';\n"
    f"const loopbackTicket = '{encrypted}';\n")
